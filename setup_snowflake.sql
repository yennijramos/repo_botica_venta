-- Ejecutar en Snowsight con un rol administrador. Sustituir TU_USUARIO_SNOWFLAKE.
CREATE WAREHOUSE IF NOT EXISTS WH_BOTICAVENTA
  WITH WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE;
CREATE DATABASE IF NOT EXISTS BOTICAVENTA_DB;
CREATE SCHEMA IF NOT EXISTS BOTICAVENTA_DB.RAW;
CREATE SCHEMA IF NOT EXISTS BOTICAVENTA_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS BOTICAVENTA_DB.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS BOTICAVENTA_DB.MARTS;
CREATE ROLE IF NOT EXISTS ROLE_BOTICAVENTA;
GRANT USAGE ON WAREHOUSE WH_BOTICAVENTA TO ROLE ROLE_BOTICAVENTA;
GRANT ALL ON DATABASE BOTICAVENTA_DB TO ROLE ROLE_BOTICAVENTA;
GRANT ALL ON ALL SCHEMAS IN DATABASE BOTICAVENTA_DB TO ROLE ROLE_BOTICAVENTA;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE BOTICAVENTA_DB TO ROLE ROLE_BOTICAVENTA;
GRANT ALL ON ALL TABLES IN SCHEMA BOTICAVENTA_DB.RAW TO ROLE ROLE_BOTICAVENTA;
GRANT ALL ON FUTURE TABLES IN SCHEMA BOTICAVENTA_DB.RAW TO ROLE ROLE_BOTICAVENTA;
GRANT ROLE ROLE_BOTICAVENTA TO USER TU_USUARIO_SNOWFLAKE;
